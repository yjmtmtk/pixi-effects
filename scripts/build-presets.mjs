// The Playground's recipe examples: each is a tested recipe of skills/pixi-effects/reference/recipes.md, wrapped as the edit block of ai/chat-template.html.
//   node scripts/build-presets.mjs        writes examples/playground/presets/recipes.js from presets/list.json (run by `npm run build:ai`; a test fails when it is stale)
// The recipe text is not changed: it sits as written inside one function, so what a person edits is what the docs and the tests run.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const RECIPES = 'skills/pixi-effects/reference/recipes.md';
export const LIST = 'examples/playground/presets/list.json';
export const OUT = 'examples/playground/presets/recipes.js';

/** What ai/chat-template.html imports from 'pixi-effects' besides Movie (a test keeps this in step with the template): importing one of these again would be an error. */
export const TEMPLATE_IMPORTS = ['kenBurns', 'withFade', 'wiggle', 'stagger', 'animateText', 'followPath', 'particles'];
/** The helpers the recipes call that the template does not import: they come from 'pixi-effects' (deck from 'pixi-effects/present'). */
const HELPERS = ['orbit', 'splitText', 'measureText', 'cameraPath', 'react', 'bpmEnvelope', 'random', 'rand', 'noise', 'noise2', 'samplePath', 'ease'];

/** The import lines a recipe body needs: the helpers it calls and does not define itself. */
function importsFor(body) {
  const uses = (n) => new RegExp(`\\b${n}\\s*\\(`).test(body) && !new RegExp(`\\b(?:const|let|var|function)\\s+${n}\\b`).test(body);
  const lines = [];
  const lib = HELPERS.filter(uses).sort();
  if (lib.length) lines.push(`import { ${lib.join(', ')} } from 'pixi-effects';`);
  if (uses('deck')) lines.push(`import { deck } from 'pixi-effects/present';`);
  return lines;
}

/** The body of the `// @recipe <id>` block in `md` (a docs-only block cannot run, so it is not one). */
export function recipeBody(md, id) {
  for (const m of md.matchAll(/```js\n\/\/ @(recipe|docs-only) ([^\n]+)\n([\s\S]*?)```/g)) {
    if (m[1] === 'recipe' && m[2].trim() === id) return m[3].replace(/\n+$/, '');
  }
  throw new Error(`no @recipe "${id}" in ${RECIPES}`);
}

/** The edit block for one list entry: { id, recipe, label, duration, background, poster }. */
export function presetCode(md, meta) {
  const body = recipeBody(md, meta.recipe).split('\n').map((l) => (l ? `  ${l}` : l)).join('\n');
  const object = /\breturn\s*\{/.test(body);                     // `{ sequences, transitions, … }` instead of an array of layers
  const head = [
    `// Recipe "${meta.recipe}" (skills/pixi-effects/reference/recipes.md). Edit anything, then press ⌘↵ / Ctrl+↵ to Run.`,
    ...importsFor(body),
    ...(importsFor(body).length ? [''] : []),
    `const W = 1280, H = 720, FPS = 30, DURATION = ${meta.duration};`,
    `const BACKGROUND = '${meta.background}';`,
    '',
  ];
  const tail = object
    ? [`const RECIPE = (() => {`, body, `})();`, `const sequences = RECIPE.sequences;`, `const INIT = { composition: { transitions: RECIPE.transitions } };`]
    : [`const sequences = (() => {`, body, `})();`];
  return [...head, ...tail, `const POSTER = ${meta.poster};`, ''].join('\n');
}

export function buildPresets(root = ROOT, list = JSON.parse(readFileSync(join(root, LIST), 'utf8'))) {
  const md = readFileSync(join(root, RECIPES), 'utf8');
  const presets = list.map((meta) => ({ id: meta.id, label: meta.label, code: presetCode(md, meta) }));
  const js = `// GENERATED by scripts/build-presets.mjs from presets/list.json and ${RECIPES}: do not edit (npm run build:ai).\n` +
    `export default ${JSON.stringify(presets, null, 2)};\n`;
  return { presets, js };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { presets, js } = buildPresets();
  writeFileSync(join(ROOT, OUT), js);
  console.log(`${OUT}: ${presets.length} presets`);
}
